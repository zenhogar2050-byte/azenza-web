import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import { PRODUCTS, PROMOTIONS, COMBO_OF_THE_MONTH, CATEGORIES } from '../src/constants';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const root = path.resolve(__dirname, '..');

async function generateStatic() {
  try {
    const templatePath = path.resolve(root, 'dist/index.html');
    if (!fs.existsSync(templatePath)) {
      console.warn('dist/index.html not found yet. Run client build first.');
      return;
    }

    const template = fs.readFileSync(templatePath, 'utf-8');
    
    // Import the ESM server bundle generated by Vite
    const serverBundlePath = path.resolve(root, 'dist/server/main-server.js');
    if (!fs.existsSync(serverBundlePath)) {
      console.warn('dist/server/main-server.js not found. Skipping static HTML pre-rendering.');
      return;
    }

    const serverModule = await import(serverBundlePath);
    if (typeof serverModule.render !== 'function') {
      console.warn('render function not found in server bundle exports:', Object.keys(serverModule));
      return;
    }

    // Build the list of static routes to pre-render
    const routesToRender: string[] = [
      '/',
      '/quienes-somos',
      '/politica-privacidad',
      '/politica-reembolso',
      '/terminos-servicio',
      '/condiciones-entrega',
      '/devoluciones-garantia',
      '/checkout',
      '/gracias'
    ];

    // Add categories
    for (const cat of CATEGORIES) {
      routesToRender.push(`/categoria/${cat.id}`);
    }
    routesToRender.push('/categoria/combos');

    // Add products
    for (const product of PRODUCTS) {
      routesToRender.push(`/producto/${product.id}`);
    }

    // Add combos
    routesToRender.push(`/combo/${COMBO_OF_THE_MONTH.id}`);
    for (const promo of PROMOTIONS) {
      routesToRender.push(`/combo/${promo.id}`);
    }

    console.log(`Pre-rendering ${routesToRender.length} static routes for Cloudflare...`);

    let renderedCount = 0;
    for (const route of routesToRender) {
      try {
        const { html: appHtml } = serverModule.render(route);
        let customizedTemplate = template;

        if (route.startsWith('/producto/')) {
          const productId = route.replace('/producto/', '');
          const prod = PRODUCTS.find(p => p.id === productId);
          if (prod) {
            const title = prod.seoTitle || `${prod.name} | AZENZA`;
            const desc = prod.seoDescription || prod.shortDescription || prod.description.slice(0, 150);
            const rawKw = [
              ...(typeof prod.keywords === 'string' ? prod.keywords.split(',').map(s => s.trim()) : (prod.keywords || [])),
              ...(prod.longTailKeywords || [])
            ].filter(Boolean);
            const kw = Array.from(new Set(rawKw)).join(', ');
            const img = prod.image.startsWith('http') ? prod.image : `https://azenza.com.co${prod.image}`;

            customizedTemplate = customizedTemplate
              .replace(/<title[^>]*>.*?<\/title>/, `<title data-rh="true">${title}</title>`)
              .replace(/<meta data-rh="true" name="description" content=".*?" \/>/, `<meta data-rh="true" name="description" content="${desc.replace(/"/g, '&quot;')}" />`)
              .replace(/<meta name="keywords" content=".*?" \/>/, `<meta name="keywords" content="${kw.replace(/"/g, '&quot;')}" />`)
              .replace(/<meta data-rh="true" property="og:title" content=".*?" \/>/, `<meta data-rh="true" property="og:title" content="${title.replace(/"/g, '&quot;')}" />`)
              .replace(/<meta data-rh="true" property="og:description" content=".*?" \/>/, `<meta data-rh="true" property="og:description" content="${desc.replace(/"/g, '&quot;')}" />`)
              .replace(/<link data-rh="true" rel="canonical" href=".*?" \/>/, `<link data-rh="true" rel="canonical" href="https://azenza.com.co${route}" />`)
              .replace(/<meta data-rh="true" property="og:url" content=".*?" \/>/, `<meta data-rh="true" property="og:url" content="https://azenza.com.co${route}" />`)
              .replace(/<meta data-rh="true" property="og:image" content=".*?" \/>/, `<meta data-rh="true" property="og:image" content="${img}" />`);
          }
        } else if (route.startsWith('/combo/')) {
          const comboId = route.replace('/combo/', '');
          const combo = comboId === COMBO_OF_THE_MONTH.id ? COMBO_OF_THE_MONTH : PROMOTIONS.find(p => p.id === comboId);
          if (combo) {
            const title = combo.seoTitle || `${combo.name} | AZENZA`;
            const desc = combo.seoDescription || combo.whyChoose?.description || combo.description.split('\n')[0];
            const rawKw = [
              ...(typeof combo.keywords === 'string' ? combo.keywords.split(',').map(s => s.trim()) : (combo.keywords || [])),
              ...(combo.longTailKeywords || [])
            ].filter(Boolean);
            const kw = Array.from(new Set(rawKw)).join(', ');
            const img = combo.image.startsWith('http') ? combo.image : `https://azenza.com.co${combo.image}`;

            customizedTemplate = customizedTemplate
              .replace(/<title[^>]*>.*?<\/title>/, `<title data-rh="true">${title}</title>`)
              .replace(/<meta data-rh="true" name="description" content=".*?" \/>/, `<meta data-rh="true" name="description" content="${desc.replace(/"/g, '&quot;')}" />`)
              .replace(/<meta name="keywords" content=".*?" \/>/, `<meta name="keywords" content="${kw.replace(/"/g, '&quot;')}" />`)
              .replace(/<meta data-rh="true" property="og:title" content=".*?" \/>/, `<meta data-rh="true" property="og:title" content="${title.replace(/"/g, '&quot;')}" />`)
              .replace(/<meta data-rh="true" property="og:description" content=".*?" \/>/, `<meta data-rh="true" property="og:description" content="${desc.replace(/"/g, '&quot;')}" />`)
              .replace(/<link data-rh="true" rel="canonical" href=".*?" \/>/, `<link data-rh="true" rel="canonical" href="https://azenza.com.co${route}" />`)
              .replace(/<meta data-rh="true" property="og:url" content=".*?" \/>/, `<meta data-rh="true" property="og:url" content="https://azenza.com.co${route}" />`)
              .replace(/<meta data-rh="true" property="og:image" content=".*?" \/>/, `<meta data-rh="true" property="og:image" content="${img}" />`);
          }
        }

        const finalHtml = customizedTemplate.replace('<div id="root"></div>', `<div id="root">${appHtml}</div>`);

        let targetFile: string;
        if (route === '/') {
          targetFile = templatePath;
        } else {
          const targetDir = path.resolve(root, 'dist', route.replace(/^\//, ''));
          if (!fs.existsSync(targetDir)) {
            fs.mkdirSync(targetDir, { recursive: true });
          }
          targetFile = path.resolve(targetDir, 'index.html');
        }

        fs.writeFileSync(targetFile, finalHtml, 'utf-8');
        renderedCount++;
      } catch (routeErr) {
        console.warn(`Could not pre-render route ${route}:`, routeErr);
      }
    }

    console.log(`Successfully pre-rendered ${renderedCount} static pages into dist/`);

    // Ensure public files exist in dist/
    const countryCodes = ['cl', 'cr', 'ec', 'gt', 'hn', 'pe', 'do', 've'];
    const countrySeoFiles = countryCodes.flatMap(c => [`sitemap-${c}.xml`, `llms-${c}.txt`, `llms-full-${c}.txt`]);
    const publicFiles = [
      'google-feed.xml', 
      'google-feed-cl.xml', 
      'google-feed-cr.xml', 
      'google-feed-ec.xml', 
      'google-feed-gt.xml', 
      'google-feed-hn.xml', 
      'google-feed-pe.xml', 
      'google-feed-do.xml', 
      'google-feed-ve.xml', 
      'llms.txt', 'llms-full.txt', 'sitemap.xml', 'sitemap_index.xml', 'robots.txt', '_redirects', '_headers', 'CNAME', '404.html',
      ...countrySeoFiles
    ];
    for (const file of publicFiles) {
      const srcFile = path.resolve(root, 'public', file);
      const dstFile = path.resolve(root, 'dist', file);
      if (fs.existsSync(srcFile)) {
        fs.copyFileSync(srcFile, dstFile);
      }
    }

  } catch (error) {
    console.error('Error during static generation:', error);
  }
}

generateStatic();
